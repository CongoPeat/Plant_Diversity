    y<-c(y,x)
  }
  
  DF_BBK1_RESAMPLED<-cbind(DF_BBK1_RESAMPLED, y)					#THEN ADD y TO THE "DF_BLACKWATER_RESAMPLED" DATAFRAME WHICH WILL END UP WITH 1000 COLUMNS OF LENGTH 300, AND CONTAINS THE NUMBER OF SPECIES 
  #FROM THE RANDOMLY SAMPLED STEMS. ROW 1 REPRESENT THE RANDOM SAMPLING WHEN THERE IS 1 STEM, 300 REPRESENTS THE RANDOM SAMPLING WITH 300 STEMS
}												#END LOOP




