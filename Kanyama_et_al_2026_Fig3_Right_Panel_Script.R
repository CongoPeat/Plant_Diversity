DF_BBK1_RESAMPLED<-c()									#CREATE EMPTY VECTOR, WHICH AS YOU LOOP THROUGH 1000 TIMES BECOMES A DATAFRAME, AS YOU KEEP APPENDING EACH OF THE 1000 RUNS


for (j in 1:1000){									#START THE 1000 LOOPS
  
  
  RESAMPLED_BBK1_PLOTS <- lapply(1:300, function(size) {			#USE LAPPLY TO RANDOMLY RESAMPLE WITH REPLACEMENT THE SPECIES DATA GOING FROM 1 STEM UP TO 300 STEMS. 300 IS SO THAT WE CAN MAKE A COMPARISON WITH MOST OTHER STUDIES.
    sample(BBK1$Species, size = size, replace = TRUE)			
  })
  
  
  y <- c()											#CREATE AN EMPTY VECTOR y, WHICH WILL CONTAIN THE NUMBER OF SPECIES IN THE 1 TO 300 RANDOMLY RESAMPLED STEMS. SO y HAS A LENGTH OF 300
  
  for (i in 1:300) {									#WE WILL USE A LOOP INSIDE THE LOOP TO RETURN THE NUMBER OF SPECIES IN THE 1 TO 300 RANDOMLY RESAMPLED STEMS
